// Writes nodes/LurkApi/operations.generated.ts from LurkAPI's OpenAPI document.
// Usage: node scripts/generate.mjs [spec path or URL]
import { writeFile } from "node:fs/promises";
import { costLine, endpoints, loadSpec, platforms, SPEC_URL } from "./spec.mjs";

const OUT = new URL("../nodes/LurkApi/operations.generated.ts", import.meta.url);
const ACRONYMS = { id: "ID", url: "URL", cdn: "CDN", ai: "AI", api: "API" };

const spec = await loadSpec(process.argv[2]);
const groups = platforms(endpoints(spec));

const resource = {
  displayName: "Resource",
  name: "resource",
  type: "options",
  noDataExpression: true,
  options: [
    ...groups.map((g) => ({ name: g.name, value: g.id })),
    { name: "Custom API Call", value: "custom", description: "Call any LurkAPI endpoint by its path, including ones newer than this node" },
  ].sort(byName),
  default: groups[0].id,
};

const props = [];
for (const g of groups) {
  props.push({
    displayName: "Operation",
    name: "operation",
    type: "options",
    noDataExpression: true,
    displayOptions: { show: { resource: [g.id] } },
    options: g.endpoints
      .map((e) => ({
        name: opName(e.title, g.name),
        value: e.id,
        action: action(g.name, opName(e.title, g.name)),
        description: sentenceDescription(`${e.summary} ${costLine(e)}`),
        routing: { request: { method: "GET", url: e.path } },
      }))
      .sort(byName),
    default: g.endpoints[0].id,
  });
  for (const e of g.endpoints) {
    const show = { resource: [g.id], operation: [e.id] };
    const optional = [];
    for (const p of e.params) {
      if (p.required) props.push({ ...field(p), required: true, displayOptions: { show } });
      else optional.push(field(p));
    }
    if (optional.length) {
      props.push({
        displayName: "Options",
        name: "options",
        type: "collection",
        placeholder: "Add option",
        default: {},
        displayOptions: { show },
        options: optional.sort((a, b) => a.displayName.localeCompare(b.displayName)),
      });
    }
  }
}

/** The editor shows the resource above the operation, so `Search Reddit` becomes `Search`. */
function opName(title, platform) {
  const t = title.replace(new RegExp(`\\s*\\b${platform.replace(/[()]/g, "\\$&")}\\b\\s*`, "i"), " ").trim();
  return t ? t[0].toUpperCase() + t.slice(1) : title;
}

function field(p) {
  const f = {
    displayName: label(p.name),
    name: p.name,
    type: p.enum ? "options" : p.type,
    default: p.default ?? (p.enum ? p.enum[0] : p.type === "number" ? 0 : p.type === "boolean" ? false : ""),
    description: sentenceDescription(p.description),
    routing: { send: { type: "query", property: p.name } },
  };
  if (p.enum) f.options = p.enum.map((v) => ({ name: label(v), value: v })).sort(byName);
  if (p.type === "string" && p.example !== undefined && p.example !== "") f.placeholder = `e.g. ${p.example}`;
  if (p.type === "boolean") f.routing.send.value = '={{ $value ? "true" : "false" }}';
  return f;
}

/** `max_cursor` → `Max Cursor`, `pageId` → `Page ID`, `past-24h` → `Past 24h`. */
function label(name) {
  return String(name)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((w) => ACRONYMS[w.toLowerCase()] ?? (/^[A-Z0-9]+$/.test(w) ? w : w[0].toUpperCase() + w.slice(1).toLowerCase()))
    .join(" ");
}

/** `TikTok` + `Profile videos` → `TikTok profile videos`; words with capitals inside (`Ad Library`, `IP`) keep them. */
function action(platform, name) {
  const words = name.split(" ").map((w, i) => (i === 0 && !/^[A-Z]{2,}|.[A-Z]/.test(w) ? w.toLowerCase() : w));
  return `${platform} ${words.join(" ")}`;
}

/** n8n's linter wants a final period only on descriptions of more than one sentence. */
function sentenceDescription(text) {
  const t = text.replace(/\s+/g, " ").trim().replace(/\.$/, "");
  return /\.\s/.test(t) ? `${t}.` : t;
}

function byName(a, b) {
  return a.name.localeCompare(b.name);
}

const header = `// Generated by scripts/generate.mjs from ${SPEC_URL}. Don't edit: run \`npm run generate\`.\n`;
const body =
  `import type { INodeProperties } from 'n8n-workflow';\n\n` +
  `export const resourceProperty: INodeProperties = ${JSON.stringify(resource, null, "\t")};\n\n` +
  `export const operationProperties: INodeProperties[] = ${JSON.stringify(props, null, "\t")};\n`;
await writeFile(OUT, header + body);
console.log(`${groups.length} resources, ${groups.reduce((n, g) => n + g.endpoints.length, 0)} operations`);
